#!/usr/bin/env python3
"""Generate firmware/decoder/include/synapsys/config_v1.hpp from the frozen fixture configs.

Source of truth: fixtures/config/{synapsys_v1,benchmark_v1}.json (written by
scripts/make_fixtures.py from the frozen Python reference v1). The C++ never re-designs
filters; it copies these coefficients.

Usage:
    gen_config.py            # (re)write the header
    gen_config.py --check    # exit 1 if the header differs from what the JSON implies,
                             # or if any numeric literal in it does not round-trip to the
                             # JSON value (catches hand edits and JSON drift)

Numbers are printed with %.17g (exact float64 round trip). Target frequencies are copied
as stored in the JSON (synapsys_v1 YES = 8.5714285714, the configs/synapsys.yaml value the
Python reference and the fixtures actually used -- NOT 60/7 to 17 digits).
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
CONFIG_DIR = REPO / "fixtures" / "config"
HEADER = REPO / "firmware" / "decoder" / "include" / "synapsys" / "config_v1.hpp"
CONFIGS = ("synapsys_v1", "benchmark_v1")

# Compile-time sizes in decoder.hpp; the JSON must agree with them.
K_CHANNELS = 4
K_TARGETS = 3
K_HARMONICS = 2
K_WINDOW = 625
K_MAX_SECTIONS = 8
HOP_SECONDS = 0.5  # decision hop (PLAN.md section 5, phase 3); 125 samples at 250 Hz
PY_RANK_TOL = 1e-10  # float64 reference value == kDefaultRankTol of the double build


def g17(x: float) -> str:
    s = f"{float(x):.17g}"
    if not any(c in s for c in ".eEn"):
        s += ".0"
    return s


def load(name: str) -> dict:
    return json.loads((CONFIG_DIR / f"{name}.json").read_text())


def validate(cfg: dict) -> None:
    name = cfg["name"]
    problems = []
    if cfg["format_version"] != 1:
        problems.append(f"format_version {cfg['format_version']} != 1")
    if len(cfg["channels"]) != K_CHANNELS:
        problems.append(f"{len(cfg['channels'])} channels != {K_CHANNELS}")
    if len(cfg["targets"]) != K_TARGETS:
        problems.append(f"{len(cfg['targets'])} targets != {K_TARGETS}")
    if cfg["harmonics"] != K_HARMONICS:
        problems.append(f"harmonics {cfg['harmonics']} != {K_HARMONICS}")
    if cfg["window_samples"] != K_WINDOW:
        problems.append(f"window_samples {cfg['window_samples']} != {K_WINDOW}")
    sos = cfg["preprocessing"]["sos"]
    if not (1 <= len(sos) <= K_MAX_SECTIONS):
        problems.append(f"{len(sos)} SOS sections not in [1, {K_MAX_SECTIONS}]")
    for row in sos:
        if len(row) != 6 or row[3] != 1.0:
            problems.append(f"bad SOS row {row}")
    if cfg["preprocessing"]["mode"] != "causal":
        problems.append("preprocessing.mode must be causal")
    if cfg["cca"]["rank_tol"] != PY_RANK_TOL:
        problems.append(f"rank_tol {cfg['cca']['rank_tol']} != {PY_RANK_TOL}")
    hop = HOP_SECONDS * cfg["sample_rate_hz"]
    if hop != int(hop):
        problems.append(f"hop {hop} samples is not an integer")
    if problems:
        raise SystemExit(f"{name}: " + "; ".join(problems))


def emit_function(cfg: dict) -> str:
    name = cfg["name"]
    pre = cfg["preprocessing"]
    lines = [
        f"// {name}: targets "
        + ", ".join(f"{t['label']} {t['frequency_hz']:g} Hz" for t in cfg["targets"])
        + f"; notch {pre['notch_hz']}; {len(pre['sos'])} SOS sections.",
        f"inline Config config_{name}() {{",
        "  Config c;",
        f"  c.sample_rate_hz = {g17(cfg['sample_rate_hz'])};",
    ]
    for i, t in enumerate(cfg["targets"]):
        lines.append(f"  c.frequencies_hz[{i}] = {g17(t['frequency_hz'])};")
        lines.append(f'  c.labels[{i}] = "{t["label"]}";')
    lines.append(f"  c.n_sections = {len(pre['sos'])};")
    for i, row in enumerate(pre["sos"]):
        vals = ", ".join(g17(v) for v in row)
        lines.append(f"  c.sos[{i}] = {{{{{vals}}}}};")
    lines.append(f"  c.remove_dc = {'true' if pre['remove_dc'] else 'false'};")
    lines.append(f"  c.hop_samples = {int(HOP_SECONDS * cfg['sample_rate_hz'])};")
    lines.append(
        "  c.rank_tol = kDefaultRankTol;  // JSON: "
        f"{g17(cfg['cca']['rank_tol'])} (float64); float build uses 1e-5"
    )
    lines.append("  // Thresholds stay unset until calibrated on own-system data.")
    lines.append("  c.has_confidence_threshold = false;")
    lines.append("  c.has_margin_threshold = false;")
    lines.append("  return c;")
    lines.append("}")
    return "\n".join(lines)


def render(cfgs: list[dict]) -> str:
    head = [
        "// GENERATED FILE -- DO NOT EDIT.",
        "// Generated by firmware/tools/gen_config.py from "
        + ", ".join(f"fixtures/config/{c['name']}.json" for c in cfgs)
        + ".",
        "// Regenerate: python firmware/tools/gen_config.py ; drift is caught by the ctest",
        "// `gen_config_check` (gen_config.py --check).",
        "#pragma once",
        "",
        '#include "synapsys/decoder.hpp"',
        "",
        "namespace synapsys {",
        "",
    ]
    body = "\n\n".join(emit_function(c) for c in cfgs)
    return "\n".join(head) + "\n" + body + "\n\n}  // namespace synapsys\n"


def literal_check(text: str, cfgs: list[dict]) -> list[str]:
    """Parse numeric literals back out of the header and compare with the JSON."""
    errs = []
    for cfg in cfgs:
        m = re.search(rf"inline Config config_{cfg['name']}\(\) \{{(.*?)\n\}}", text, re.S)
        if not m:
            errs.append(f"config_{cfg['name']}() not found")
            continue
        body = m.group(1)
        for i, t in enumerate(cfg["targets"]):
            f = re.search(rf"c\.frequencies_hz\[{i}\] = ([^;]+);", body)
            if not f or float(f.group(1)) != float(t["frequency_hz"]):
                errs.append(f"{cfg['name']} frequency {i} mismatch")
            lab = re.search(rf'c\.labels\[{i}\] = "([^"]*)";', body)
            if not lab or lab.group(1) != t["label"]:
                errs.append(f"{cfg['name']} label {i} mismatch")
        sos = cfg["preprocessing"]["sos"]
        n = re.search(r"c\.n_sections = (\d+);", body)
        if not n or int(n.group(1)) != len(sos):
            errs.append(f"{cfg['name']} n_sections mismatch")
        for i, row in enumerate(sos):
            r = re.search(rf"c\.sos\[{i}\] = \{{\{{([^}}]*)\}}\}};", body)
            if not r:
                errs.append(f"{cfg['name']} sos row {i} missing")
                continue
            vals = [float(v) for v in r.group(1).split(",")]
            if vals != [float(v) for v in row]:
                errs.append(f"{cfg['name']} sos row {i} mismatch: {vals} vs {row}")
        fs = re.search(r"c\.sample_rate_hz = ([^;]+);", body)
        if not fs or float(fs.group(1)) != float(cfg["sample_rate_hz"]):
            errs.append(f"{cfg['name']} sample rate mismatch")
    return errs


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="verify instead of writing")
    ap.add_argument("--header", type=Path, default=HEADER)
    args = ap.parse_args()

    cfgs = [load(n) for n in CONFIGS]
    for c in cfgs:
        validate(c)
    text = render(cfgs)

    if args.check:
        if not args.header.exists():
            print(f"FAIL: {args.header} missing", file=sys.stderr)
            return 1
        current = args.header.read_text()
        errs = literal_check(current, cfgs)
        if current != text:
            errs.append("header text differs from generator output (hand edit or JSON drift)")
        if errs:
            for e in errs:
                print("FAIL:", e, file=sys.stderr)
            return 1
        print(f"OK: {args.header.name} matches {', '.join(CONFIGS)}")
        return 0

    args.header.write_text(text)
    print(f"wrote {args.header}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
